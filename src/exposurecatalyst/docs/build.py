"""Documentation pipeline: `python -m exposurecatalyst.docs build`.

Steps
  1. Generate reference pages from code (configuration reference, RBAC matrix) — no drift.
  2. Render every diagram in docs/diagrams/*.py → SVG (embedded icons) + 300-DPI PNG + .drawio.
  3. Build the MkDocs Material site with --strict (broken links / missing files fail the build).
Phase 6 adds: standalone single-file HTML and DOCX (Pandoc + reference.docx) for each audience guide.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess  # noqa: S404  # nosec B404
import sys
from datetime import UTC, datetime
from pathlib import Path

from exposurecatalyst import __version__
from exposurecatalyst.config import PROJECT_ROOT, Settings
from exposurecatalyst.security.rbac import DEFAULT_ROLES, PERMISSION_DESCRIPTIONS, Permission

DOCS = PROJECT_ROOT / "docs"
DIAGRAMS = DOCS / "diagrams"
DIAGRAM_OUT = DOCS / "assets" / "diagrams"
DIST = PROJECT_ROOT / "dist" / "docs"
GENERATED_BANNER = "<!-- GENERATED by `python -m exposurecatalyst.docs build` — do not edit by hand. -->\n\n"


def gen_configuration_reference() -> Path:
    lines = [GENERATED_BANNER, "# Configuration reference\n\n",
             "Every setting is an environment variable with the `EXCAT_` prefix (also read from `.env`). "
             "Secrets should come from AWS Secrets Manager / your vault, never from source control.\n\n",
             "| Variable | Type | Default | Description |\n|---|---|---|---|\n"]
    for name, field in Settings.model_fields.items():
        ann = getattr(field.annotation, "__name__", None) or str(field.annotation).replace("typing.", "")
        default = field.default
        if hasattr(default, "get_secret_value"):
            default = "*(secret)*" if "database" not in name else "`sqlite:///./exposurecatalyst.db`"
        elif isinstance(default, Path):
            default = f"`{default.relative_to(PROJECT_ROOT)}`" if default.is_relative_to(PROJECT_ROOT) else default
        elif default is None:
            default = "—"
        else:
            default = f"`{default}`"
        desc = (field.description or "").replace("|", "\\|")
        lines.append(f"| `EXCAT_{name.upper()}` | `{ann}` | {default} | {desc} |\n")
    out = DOCS / "reference" / "configuration.md"
    out.write_text("".join(lines), encoding="utf-8")
    return out


def gen_rbac_matrix() -> Path:
    roles = list(DEFAULT_ROLES)
    lines = [GENERATED_BANNER, "# Roles × permissions matrix\n\n",
             "Default system roles. System roles are read-only; create custom roles in "
             "**Settings → RBAC** (requires `role:manage`).\n\n",
             "| Permission | Description | " + " | ".join(roles) + " |\n",
             "|---|---|" + "|".join([":-:"] * len(roles)) + "|\n"]
    for p in Permission:
        marks = " | ".join("✅" if p in DEFAULT_ROLES[r][1] else "—" for r in roles)
        lines.append(f"| `{p}` | {PERMISSION_DESCRIPTIONS[p]} | {marks} |\n")
    lines.append("\n## Role descriptions\n\n")
    for r, (desc, _) in DEFAULT_ROLES.items():
        lines.append(f"- **{r}** — {desc}\n")
    out = DOCS / "reference" / "rbac-matrix.md"
    out.write_text("".join(lines), encoding="utf-8")
    return out


def render_diagrams(use_docker: bool) -> None:
    scripts = sorted(p for p in DIAGRAMS.glob("*.py") if not p.name.startswith("_"))
    if not scripts:
        return
    DIAGRAM_OUT.mkdir(parents=True, exist_ok=True)
    if shutil.which("dot") is None or use_docker:
        if shutil.which("docker") is None:
            raise SystemExit("Graphviz `dot` not found and Docker unavailable — cannot render diagrams.")
        _run(["docker", "build", "-q", "-t", "exposurecatalyst-diagrams", "-f",
              str(PROJECT_ROOT / "docker" / "diagrams.Dockerfile"), str(PROJECT_ROOT / "docker")])
        _run(["docker", "run", "--rm", "-v", f"{DOCS}:/docs", "-w", "/docs/diagrams",
              "exposurecatalyst-diagrams", "python", "_render_all.py", "/docs/assets/diagrams"])
    else:
        _run([sys.executable, str(DIAGRAMS / "_render_all.py"), str(DIAGRAM_OUT)], cwd=DIAGRAMS)
    for script in scripts:
        for ext in ("svg", "png", "drawio"):
            f = DIAGRAM_OUT / f"{script.stem}.{ext}"
            if not f.exists() or f.stat().st_size == 0:
                raise SystemExit(f"Diagram output missing: {f}")


def build_site(strict: bool) -> Path:
    site = DIST / "site"
    env = {**os.environ, "EXCAT_DOCS_VERSION": __version__,
           "EXCAT_DOCS_DATE": datetime.now(UTC).strftime("%Y-%m-%d")}
    cmd = [sys.executable, "-m", "mkdocs", "build", "-f", str(PROJECT_ROOT / "mkdocs.yml"), "-d", str(site)]
    if strict:
        cmd.append("--strict")
    _run(cmd, env=env)
    return site


def _run(cmd: list[str], **kw) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, **kw)  # noqa: S603  # nosec B603


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m exposurecatalyst.docs")
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="Regenerate diagrams, reference pages and the docs site")
    b.add_argument("--skip-diagrams", action="store_true", help="Use committed diagram renders")
    b.add_argument("--docker", action="store_true", help="Force diagram rendering in Docker")
    b.add_argument("--no-strict", action="store_true")
    sub.add_parser("generate", help="Only regenerate code-derived reference pages")
    sub.add_parser("diagrams", help="Only render diagrams")
    args = p.parse_args(argv)

    gen_configuration_reference()
    gen_rbac_matrix()
    if args.cmd == "generate":
        return 0
    if args.cmd == "diagrams" or (args.cmd == "build" and not args.skip_diagrams):
        render_diagrams(use_docker=getattr(args, "docker", False))
    if args.cmd == "build":
        site = build_site(strict=not args.no_strict)
        print(f"Docs built → {site}")
    return 0
