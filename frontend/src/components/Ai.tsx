import { useState, type ReactNode } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { useMutation, useQuery } from "@tanstack/react-query";
import { api } from "../api";
import { useAuth } from "../auth";
import { ErrorNote } from "./ui";

export interface AiResult { text: string; provider: string; model: string; redacted_values: number; fallbacks: string[] }

/** True only when an admin enabled AI, a provider is routed, and the user holds ai:use. */
export function useAi() {
  const { me } = useAuth();
  const q = useQuery({ queryKey: ["ai-status"], queryFn: () => api<{ enabled: boolean }>("/api/ai/status"), enabled: !!me, staleTime: 60_000 });
  return Boolean(q.data?.enabled);
}

/**
 * Renders model output as Markdown with NO raw HTML and NO images (blocks the classic
 * "markdown image → attacker URL" exfiltration channel; CSP img-src is 'self' as a second layer).
 */
export function AiText({ text }: { text: string }) {
  return (
    <div className="prose-help">
      <ReactMarkdown remarkPlugins={[remarkGfm]} components={{
        img: () => null,
        a: ({ href, children }) => <a href={href} target="_blank" rel="noopener noreferrer nofollow">{children}</a>,
      }}>{text}</ReactMarkdown>
    </div>
  );
}

export function AiMeta({ r }: { r: Pick<AiResult, "provider" | "model" | "redacted_values" | "fallbacks"> }) {
  return (
    <p className="mt-2 border-t border-ec-border pt-2 text-[11px] text-ec-slate">
      AI-generated by {r.provider} · {r.model}{r.redacted_values > 0 && ` · ${r.redacted_values} identifier(s) redacted before sending`}
      {r.fallbacks.length > 0 && ` · fell back after: ${r.fallbacks.join("; ")}`} — verify before acting.
    </p>
  );
}

export function AiBox({ title, children, actions }: { title: string; children: ReactNode; actions?: ReactNode }) {
  return (
    <section className="card border-l-4 border-l-ec-orange">
      <div className="mb-2 flex flex-wrap items-center justify-between gap-2">
        <h2 className="flex items-center gap-2 font-heading font-bold"><span aria-hidden="true" className="rounded-sm bg-ec-navy px-1.5 py-0.5 text-[10px] font-bold text-white">AI</span>{title}</h2>
        {actions}
      </div>
      {children}
    </section>
  );
}

const KINDS = [["plain", "Plain English"], ["executive", "Executive"], ["risk", "Risk narrative"], ["remediation", "Remediation"]] as const;

export function CveAiPanel({ cveId }: { cveId: string }) {
  const [kind, setKind] = useState<string | null>(null);
  const m = useMutation({ mutationFn: (k: string) => api<AiResult>(`/api/ai/cves/${encodeURIComponent(cveId)}/insight`, { method: "POST", body: { kind: k } }) });
  return (
    <AiBox title="AI analysis" actions={<span className="flex flex-wrap gap-1">{KINDS.map(([k, l]) => (
      <button key={k} className={kind === k ? "btn-primary" : "btn-secondary"} disabled={m.isPending} onClick={() => { setKind(k); m.mutate(k); }}>{l}</button>))}</span>}>
      {m.isPending && <p className="text-sm text-ec-slate">Thinking…</p>}
      <ErrorNote error={m.error} />
      {m.data ? <><AiText text={m.data.text} /><AiMeta r={m.data} /></> : !m.isPending && <p className="text-sm text-ec-slate">Choose an analysis. Asset identifiers are redacted before data is sent to external models, per your organization's policy.</p>}
    </AiBox>
  );
}
